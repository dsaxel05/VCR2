"""Every company data room of a corpus set dropped on the real Smart fill zone in Chromium (real drag-and-drop events), read
with "Read my documents", then scored against the gold: what the review page proposes is what the visitor gets.
    python tests/smartfill/browser_drop.py blind2611            (dev tool; the corpus is generated by run.mjs, not committed)"""
import asyncio, base64, functools, http.server, json, pathlib, socket, sys, threading, collections
from playwright.async_api import async_playwright
ROOT = pathlib.Path(__file__).resolve().parents[2]; SET = sys.argv[1] if len(sys.argv) > 1 else 'blind2611'
D = ROOT / 'tests' / 'smartfill' / 'corpus' / SET; gold = json.loads((D / 'gold.json').read_text(encoding='utf-8'))

class Q(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *a): pass
s = socket.socket(); s.bind(('127.0.0.1', 0)); port = s.getsockname()[1]; s.close()
httpd = http.server.ThreadingHTTPServer(('127.0.0.1', port), functools.partial(Q, directory=str(ROOT)))
threading.Thread(target=httpd.serve_forever, daemon=True).start()

DROP = """(files) => { const dt = new DataTransfer(); for (const [n, b] of files) dt.items.add(new File([Uint8Array.from(atob(b), c => c.charCodeAt(0))], n));
  $id('sf-drop').dispatchEvent(new DragEvent('drop', { dataTransfer:dt, bubbles:true, cancelable:true })); }"""
def same(a, b):
    if isinstance(b, bool) or isinstance(a, bool): return a == b
    if isinstance(b, (int, float)): return isinstance(a, (int, float)) and abs(a - b) <= max(abs(b) * 0.006, 0.051)
    return str(a).strip().lower() == str(b).strip().lower()

async def main():
    by = collections.defaultdict(list)
    for d in gold['docs']: by[d['file'].split('/')[0]].append(d)
    tot = dict(docs=0, added=0, read=0, gold=0, found=0, wrong=0, wrongHigh=0); misses = []; errs = []
    async with async_playwright() as p:
        b = await p.chromium.launch(); pg = await b.new_page()
        pg.on('pageerror', lambda e: errs.append(str(e))); pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' else None)
        await pg.goto(f'http://127.0.0.1:{port}/index.html'); await pg.wait_for_selector('#api-key', state='attached')
        for co, docs in sorted(by.items()):
            await pg.evaluate("() => { window.confirm = () => true; sfForget(); resetApp(); showPage('intake'); renderIntakeStatus(); }")
            await pg.evaluate("(m) => { S.model = m; }", docs[0]['model'])   # the visitor picks the business model first
            files = [[d['file'].split('/')[-1], base64.b64encode((D / d['file']).read_bytes()).decode()] for d in docs]
            await pg.evaluate(DROP, files); await pg.wait_for_timeout(200)
            tot['docs'] += len(docs); tot['added'] += await pg.evaluate("() => SFS.files.length")
            await pg.click('#sf-read'); await pg.wait_for_function("() => !SFS.reading && SFS.resolved", timeout=120000)
            tot['read'] += await pg.evaluate("() => SFS.files.filter(f => f.res ? f.res.ok : f.extract || f.inWorker).length")
            rows = await pg.evaluate("() => SFS.resolved.rows.map(r => ({ f:r.field, v:r.value, t:r.tier }))")
            prop = {r['f']: r for r in rows}
            want = collections.defaultdict(list)
            for d in docs:
                for k, g in d['fields'].items(): want[k].append(g)
            for k, gs in want.items():
                tot['gold'] += 1; r = prop.get(k)
                if k == '__ledger__': tot['gold'] -= 1; continue
                if r and any(same(r['v'], g['value']) and (r['t'] != 'Low' or g['tier'] == 'Low') for g in gs): tot['found'] += 1
                else:
                    misses.append(f"{co} {k}: want {gs[0]['value']}, got {r['v'] if r else 'nothing'}{' (' + r['t'] + ')' if r else ''}")
                    if r and r['t'] != 'Low' and not any(same(r['v'], g['value']) for g in gs):
                        tot['wrong'] += 1; tot['wrongHigh'] += r['t'] == 'High'
        await b.close()
    print(json.dumps(tot)); print('recall %.1f%%' % (100 * tot['found'] / tot['gold']))
    print('\n'.join(misses[:60])); print('page errors:', errs[:5])

asyncio.run(main())
